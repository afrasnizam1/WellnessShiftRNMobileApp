export function fitnessModuleIonIcon(module: Pick<FitnessModule, 'id' | 'category' | 'wellnessCategory'>): IoniconName {
  if (MODULE_OVERRIDES[module.id]) return MODULE_OVERRIDES[module.id];
  // Education topics share a wellness category, so that fallback painted the same person icon on every row.
  if (module.category === 'education') return 'book-outline';
  if (module.wellnessCategory) return categoryIonIcon(module.wellnessCategory);
  return CATEGORY_DEFAULTS[module.category] ?? 'apps-outline';
}
