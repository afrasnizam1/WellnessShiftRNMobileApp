#!/usr/bin/env node
/**
 * Bundles src/hologram/wellnessSphere.ts (three.js) into a self-contained HTML page and
 * writes it as a TypeScript string module, so the Body HUD WebView works offline on both
 * iOS and Android with no native asset wiring.
 *
 *   npm run bundle:sphere
 */
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const entry = resolve(root, 'src/hologram/wellnessSphere.ts');
const out = resolve(root, 'src/components/home/bodyHud/wellnessSphereHtml.ts');

const result = await build({
  entryPoints: [entry],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['safari15', 'chrome90'],
  minify: true,
  legalComments: 'inline',
  write: false,
});

const js = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');

const html = `<!doctype html>
<html><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no">
<style>
html,body{margin:0;height:100%;background:transparent;overflow:hidden;-webkit-user-select:none;user-select:none;-webkit-tap-highlight-color:transparent}
#orb{position:absolute;inset:0;width:100%;height:100%;display:block;touch-action:pan-y}
#fallback{position:absolute;inset:0;display:none;align-items:center;justify-content:center;padding:24px;text-align:center;color:#A3ACB9;font:14px -apple-system,system-ui,sans-serif}
</style></head>
<body><canvas id="orb"></canvas><div id="fallback">3D view needs WebGL, which isn't available on this device.</div>
<script>${js}</script></body></html>`;

const banner = `/* eslint-disable */
// AUTO-GENERATED by scripts/build-wellness-sphere.mjs from src/hologram/wellnessSphere.ts.
// Do not edit by hand — run \`npm run bundle:sphere\` after changing the sphere source.
`;

writeFileSync(out, `${banner}export const WELLNESS_SPHERE_HTML = ${JSON.stringify(html)};\n`);
console.log(`wellnessSphereHtml.ts written (${(html.length / 1024).toFixed(0)} KB)`);
